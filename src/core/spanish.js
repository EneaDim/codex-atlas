export function translateStatisticsItalian(value = '') {
  if (!value) return value;
  if (STAT_EXACT[value]) return STAT_EXACT[value];
  let out = value;
  for (const [it, es] of IT_ES_PHRASES) {
    if (out === it) return es;
    out = out.replaceAll(it, es);
  }
  out = out.split(/(\s+|[“”"'’.,;:!?()\[\]{}·=+−×/<>≤≥])/).map((part) => {
    const key = part.toLocaleLowerCase('it');
    const es = STAT_WORDS[key];
    if (!es) return part;
    if (part[0] && part[0] === part[0].toUpperCase()) return es.charAt(0).toUpperCase() + es.slice(1);
    return es;
  }).join('');
  return out
    .replaceAll(' è ', ' es ')
    .replaceAll(' sono ', ' son ')
    .replaceAll(' ha ', ' tiene ')
    .replaceAll(' hanno ', ' tienen ')
    .replaceAll(' viene ', ' se ')
    .replaceAll(' vengono ', ' se ')
    .replaceAll(' dell’', ' de la ')
    .replaceAll(' all’', ' al ')
    .replaceAll(' nell’', ' en el ')
    .replaceAll(' l’', ' el ')
    .replaceAll(' L’', ' El ')
    .replaceAll(' dall’', ' desde el ')
    .replaceAll(' nell', ' en el');
}

function ensureLocalized(value, es) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return;
  if (!value.es) value.es = es;
}

function translateLocalizedTree(value) {
  if (!value || typeof value !== 'object') return;
  if (!Array.isArray(value) && typeof value.it === 'string' && !value.es) {
    value.es = translateStatisticsItalian(value.it);
  }
  if (Array.isArray(value)) value.forEach(translateLocalizedTree);
  else Object.values(value).forEach(translateLocalizedTree);
}

export function applySpanishBase(pack) {
  if (!pack || pack.__spanishBaseApplied) return pack;
  const meta = PACK_META[pack.id] || {};
  ensureLocalized(pack.title, meta.title || fallbackSpanishTitle(pack.title?.it || pack.title?.en || pack.id));
  ensureLocalized(pack.centerLabel, meta.centerLabel || fallbackSpanishTitle(pack.centerLabel?.it || pack.centerLabel?.en || 'CODEX'));
  ensureLocalized(pack.subtitle, meta.subtitle || `Mapa interactivo de ${pack.title.es}.`);
  if (pack.resourceNote) ensureLocalized(pack.resourceNote, meta.resourceNote || 'Contenido educativo general. Consulta fuentes oficiales y profesionales cualificados cuando corresponda.');

  localizeResources(pack.resources);
  for (const domain of pack.domains || []) {
    localizeResources(domain.resources);
    ensureLocalized(domain.title, STRUCTURE_TITLES[domain.id] || fallbackSpanishTitle(domain.title?.it || domain.title?.en || domain.id));
    ensureLocalized(domain.description, `Área que reúne los conceptos principales de ${domain.title.es}.`);
    for (const system of domain.systems || []) {
      localizeResources(system.resources);
      ensureLocalized(system.title, STRUCTURE_TITLES[system.id] || fallbackSpanishTitle(system.title?.it || system.title?.en || system.id));
      ensureLocalized(system.description, `Subtema dedicado a ${system.title.es}, dentro de ${domain.title.es}.`);
      for (const concept of system.concepts || []) {
        localizeResources(concept.resources);
        const statTitle = pack.id === 'statistics' ? STATISTICS_TITLES[concept.id] : null;
        ensureLocalized(concept.title, statTitle || fallbackSpanishTitle(concept.title?.it || concept.title?.en || concept.id));
        if (concept.wiki && !concept.wiki.es && concept.title?.es) concept.wiki.es = concept.title.es;
        if (concept.description) ensureLocalized(concept.description, pack.id === 'statistics'
          ? translateStatisticsItalian(concept.description.it || concept.description.en || '')
          : `Concepto relacionado con ${system.title.es}.`);
        if (concept.aliases && typeof concept.aliases === 'object' && !Array.isArray(concept.aliases) && !concept.aliases.es) {
          concept.aliases.es = [...(concept.aliases.it || []), ...(concept.aliases.en || [])];
        }
        if (concept.searchTerms && typeof concept.searchTerms === 'object' && !Array.isArray(concept.searchTerms) && !concept.searchTerms.es) {
          concept.searchTerms.es = [...(concept.searchTerms.it || []), ...(concept.searchTerms.en || [])];
        }
        if (pack.id === 'statistics' && concept.study) translateLocalizedTree(concept.study);
        if (concept.resources) {
          for (const resource of concept.resources) {
            if (resource.title) ensureLocalized(resource.title, fallbackSpanishTitle(resource.title.it || resource.title.en || 'Recurso'));
          }
        }
      }
    }
  }
  Object.defineProperty(pack, '__spanishBaseApplied', { value: true, enumerable: false });
  return pack;
}

export function applySpanishBaseToPacks(packs) {
  Object.values(packs).forEach(applySpanishBase);
  return packs;
}
